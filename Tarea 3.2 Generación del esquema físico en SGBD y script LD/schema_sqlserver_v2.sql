
USE Clinica;
GO

-- 1. ELIMINACIÓN LIMPIA DE TABLAS (Orden Inverso a Dependencias)
IF OBJECT_ID('dbo.RECETA_MEDICAMENTO', 'U') IS NOT NULL DROP TABLE dbo.RECETA_MEDICAMENTO;
IF OBJECT_ID('dbo.MEDICAMENTO', 'U') IS NOT NULL DROP TABLE dbo.MEDICAMENTO;
IF OBJECT_ID('dbo.RECETA', 'U') IS NOT NULL DROP TABLE dbo.RECETA;
IF OBJECT_ID('dbo.CONSULTA', 'U') IS NOT NULL DROP TABLE dbo.CONSULTA;
IF OBJECT_ID('dbo.CITA', 'U') IS NOT NULL DROP TABLE dbo.CITA;
IF OBJECT_ID('dbo.MEDICO_ESPECIALIDAD', 'U') IS NOT NULL DROP TABLE dbo.MEDICO_ESPECIALIDAD;
IF OBJECT_ID('dbo.MEDICO', 'U') IS NOT NULL DROP TABLE dbo.MEDICO;
IF OBJECT_ID('dbo.DEPARTAMENTO', 'U') IS NOT NULL DROP TABLE dbo.DEPARTAMENTO;
IF OBJECT_ID('dbo.PACIENTE', 'U') IS NOT NULL DROP TABLE dbo.PACIENTE;
IF OBJECT_ID('dbo.PERSONA_TELEFONO', 'U') IS NOT NULL DROP TABLE dbo.PERSONA_TELEFONO;
IF OBJECT_ID('dbo.PERSONA', 'U') IS NOT NULL DROP TABLE dbo.PERSONA;
GO

-- TABLA 1: PERSONA (Entidad Superclase)
CREATE TABLE PERSONA (
    ID_Persona INT IDENTITY(1,1) NOT NULL,
    Primer_Nombre VARCHAR(50) NOT NULL,
    Apellido_Paterno VARCHAR(50) NOT NULL,
    Apellido_Materno VARCHAR(50) NULL,
    Calle VARCHAR(100) NOT NULL,
    Numero VARCHAR(20) NOT NULL,
    Colonia VARCHAR(100) NOT NULL,
    Codigo_Postal VARCHAR(5) NOT NULL,
    Fecha_Nacimiento DATE NOT NULL,
    Edad_Derivado INT NULL,
    CONSTRAINT PK_Persona PRIMARY KEY CLUSTERED (ID_Persona)
);
GO

-- TABLA 2: PERSONA_TELEFONO (Atributo Multivalorado)
CREATE TABLE PERSONA_TELEFONO (
    ID_Persona INT NOT NULL,
    Telefono VARCHAR(15) NOT NULL,
    CONSTRAINT PK_PersonaTelefono PRIMARY KEY CLUSTERED (ID_Persona, Telefono),
    CONSTRAINT FK_PersonaTelefono_Persona 
        FOREIGN KEY (ID_Persona) REFERENCES PERSONA(ID_Persona)
        ON DELETE CASCADE ON UPDATE CASCADE
);
GO

-- TABLA 3: PACIENTE (Subclase 1:1 con FK UNIQUE)
CREATE TABLE PACIENTE (
    Num_Expediente VARCHAR(20) NOT NULL,
    ID_Persona INT NOT NULL,
    Tipo_Sangre VARCHAR(5) NOT NULL,
    CONSTRAINT PK_Paciente PRIMARY KEY CLUSTERED (Num_Expediente),
    CONSTRAINT UQ_Paciente_Persona UNIQUE (ID_Persona),
    CONSTRAINT FK_Paciente_Persona 
        FOREIGN KEY (ID_Persona) REFERENCES PERSONA(ID_Persona)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT CHK_Paciente_TipoSangre 
        CHECK (Tipo_Sangre IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'))
);
GO

-- TABLA 4: DEPARTAMENTO (Entidad Fuerte / Catálogo)
CREATE TABLE DEPARTAMENTO (
    ID_Depto INT IDENTITY(1,1) NOT NULL,
    Nombre_Depto VARCHAR(100) NOT NULL,
    Ubicacion VARCHAR(100) NOT NULL,
    CONSTRAINT PK_Departamento PRIMARY KEY CLUSTERED (ID_Depto),
    CONSTRAINT UQ_Departamento_Nombre UNIQUE (Nombre_Depto)
);
GO

-- TABLA 5: MEDICO (Subclase 1:1)
CREATE TABLE MEDICO (
    Num_Cedula VARCHAR(20) NOT NULL,
    ID_Persona INT NOT NULL,
    Fecha_Contratacion DATE NOT NULL,
    ID_Depto INT NOT NULL,
    CONSTRAINT PK_Medico PRIMARY KEY CLUSTERED (Num_Cedula),
    CONSTRAINT UQ_Medico_Persona UNIQUE (ID_Persona),
    CONSTRAINT FK_Medico_Persona 
        FOREIGN KEY (ID_Persona) REFERENCES PERSONA(ID_Persona)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_Medico_Depto 
        FOREIGN KEY (ID_Depto) REFERENCES DEPARTAMENTO(ID_Depto)
        ON DELETE NO ACTION ON UPDATE NO ACTION
);
GO

-- TABLA 6: MEDICO_ESPECIALIDAD (Atributo Multivalorado)
CREATE TABLE MEDICO_ESPECIALIDAD (
    Num_Cedula VARCHAR(20) NOT NULL,
    Especialidad VARCHAR(100) NOT NULL,
    CONSTRAINT PK_MedicoEspecialidad PRIMARY KEY CLUSTERED (Num_Cedula, Especialidad),
    CONSTRAINT FK_MedicoEspecialidad_Medico 
        FOREIGN KEY (Num_Cedula) REFERENCES MEDICO(Num_Cedula)
        ON DELETE CASCADE ON UPDATE CASCADE
);
GO

-- TABLA 7: CITA (Entidad Transaccional 1:N)
-- Solución al Error 1785: Se utiliza NO ACTION en ambas FKs para evitar las múltiples rutas 
-- de cascada desde PERSONA hacia CITA a través de PACIENTE y MEDICO simultáneamente.
CREATE TABLE CITA (
    Folio_Cita INT IDENTITY(1,1) NOT NULL,
    Fecha DATE NOT NULL,
    Hora TIME NOT NULL,
    Estado VARCHAR(20) NOT NULL CONSTRAINT DF_Cita_Estado DEFAULT 'Programada',
    Num_Expediente VARCHAR(20) NOT NULL,
    Num_Cedula VARCHAR(20) NOT NULL,
    CONSTRAINT PK_Cita PRIMARY KEY CLUSTERED (Folio_Cita),
    CONSTRAINT FK_Cita_Paciente 
        FOREIGN KEY (Num_Expediente) REFERENCES PACIENTE(Num_Expediente)
        ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT FK_Cita_Medico 
        FOREIGN KEY (Num_Cedula) REFERENCES MEDICO(Num_Cedula)
        ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT CHK_Cita_Estado 
        CHECK (Estado IN ('Programada', 'Completada', 'Cancelada'))
);
GO

-- TABLA 8: CONSULTA (Agregación 1:1 con CITA)
CREATE TABLE CONSULTA (
    ID_Consulta INT IDENTITY(1,1) NOT NULL,
    Folio_Cita INT NOT NULL,
    Diagnostico VARCHAR(MAX) NOT NULL,
    Costo_Base DECIMAL(10,2) NOT NULL,
    CONSTRAINT PK_Consulta PRIMARY KEY CLUSTERED (ID_Consulta),
    CONSTRAINT UQ_Consulta_Cita UNIQUE (Folio_Cita),
    CONSTRAINT FK_Consulta_Cita 
        FOREIGN KEY (Folio_Cita) REFERENCES CITA(Folio_Cita)
        ON DELETE CASCADE ON UPDATE NO ACTION,
    CONSTRAINT CHK_Consulta_Costo 
        CHECK (Costo_Base >= 0)
);
GO

-- TABLA 9: RECETA (Entidad Transaccional)
CREATE TABLE RECETA (
    Folio_Receta INT IDENTITY(1,1) NOT NULL,
    ID_Consulta INT NOT NULL,
    Fecha_Emision DATE NOT NULL CONSTRAINT DF_Receta_Fecha DEFAULT CAST(GETDATE() AS DATE),
    CONSTRAINT PK_Receta PRIMARY KEY CLUSTERED (Folio_Receta),
    CONSTRAINT FK_Receta_Consulta 
        FOREIGN KEY (ID_Consulta) REFERENCES CONSULTA(ID_Consulta)
        ON DELETE CASCADE ON UPDATE NO ACTION
);
GO

-- TABLA 10: MEDICAMENTO (Catálogo)
CREATE TABLE MEDICAMENTO (
    Codigo_Med INT IDENTITY(1,1) NOT NULL,
    Nombre_Comercial VARCHAR(100) NOT NULL,
    Formula VARCHAR(200) NOT NULL,
    CONSTRAINT PK_Medicamento PRIMARY KEY CLUSTERED (Codigo_Med)
);
GO

-- TABLA 11: RECETA_MEDICAMENTO (Tabla Intermedia N:M)
CREATE TABLE RECETA_MEDICAMENTO (
    Folio_Receta INT NOT NULL,
    Codigo_Med INT NOT NULL,
    Dosis VARCHAR(100) NOT NULL,
    Frecuencia VARCHAR(100) NOT NULL,
    Duracion_Dias INT NOT NULL,
    CONSTRAINT PK_RecetaMedicamento PRIMARY KEY CLUSTERED (Folio_Receta, Codigo_Med),
    CONSTRAINT FK_RecetaMed_Receta 
        FOREIGN KEY (Folio_Receta) REFERENCES RECETA(Folio_Receta)
        ON DELETE CASCADE ON UPDATE NO ACTION,
    CONSTRAINT FK_RecetaMed_Medicamento 
        FOREIGN KEY (Codigo_Med) REFERENCES MEDICAMENTO(Codigo_Med)
        ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT CHK_RecetaMed_Duracion 
        CHECK (Duracion_Dias > 0)
);
GO
